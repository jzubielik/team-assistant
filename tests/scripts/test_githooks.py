"""The committed git hooks: commit message rules and the pre-push guard for main."""

import os
import shutil
import subprocess
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
HOOKS = ROOT / ".githooks"
ZERO = "0" * 40

pytestmark = pytest.mark.skipif(shutil.which("bash") is None, reason="bash not installed")


def _commit_msg(tmp_path, message):
    f = tmp_path / "COMMIT_EDITMSG"
    f.write_text(message)
    return subprocess.run(
        [str(HOOKS / "commit-msg"), str(f)], capture_output=True, text=True, check=False
    )


@pytest.mark.parametrize(
    "message",
    [
        "feat: add a tool\n",
        "fix(ops): refuse a deploy without ENV\n\nBody text.\n",
        "docs(runbook): explain make leaks\n",
        "build(runner)!: require Docker 29\n",
        "ci: pin actions\n",
        "chore(deps): bump boto3\n",
        "refactor(agent/tools): split handlers\n",
        "test: cover the hooks\n",
        "perf: cache the index\n",
        "revert: feat: add a tool\n",
        "# a comment git strips\nfeat: subject after a comment\n",
        "Merge branch 'main' into mvp\n",
        'Revert "feat: add a tool"\n',
        "fixup! feat: add a tool\n",
        "squash! feat: add a tool\n",
        "feat: " + "x" * 66 + "\n",  # exactly 72
    ],
)
def test_commit_msg_accepts(tmp_path, message):
    r = _commit_msg(tmp_path, message)
    assert r.returncode == 0, r.stderr


@pytest.mark.parametrize(
    ("message", "reason"),
    [
        ("Add a tool\n", "not 'type(scope)?!?: subject'"),
        ("feature: add a tool\n", "known type"),
        ("feat:add a tool\n", "known type"),
        ("feat(Ops): add a tool\n", "known type"),
        ("feat: add a tool.\n", "ends with a period"),
        ("feat: " + "x" * 67 + "\n", "73 characters"),
        ("\n# only a comment\n", "empty"),
    ],
)
def test_commit_msg_rejects_with_examples(tmp_path, message, reason):
    r = _commit_msg(tmp_path, message)
    assert r.returncode == 1
    assert reason in r.stderr
    assert "Examples:" in r.stderr and "docs(runbook):" in r.stderr


# The rule names no vendor: any co-author trailer and any "Generated with/by" line is refused,
# whichever tool wrote it.
@pytest.mark.parametrize(
    "line",
    [
        "Co-Authored-By: someone",
        "co-authored-by: Some Agent <agent@example.com>",
        "Generated with a tool",
        "\U0001f916 Generated with [Some Tool](https://example.com)",
        "Generated by an agent",
    ],
)
def test_commit_msg_rejects_attribution(tmp_path, line):
    r = _commit_msg(tmp_path, f"feat: add a tool\n\n{line}\n")
    assert r.returncode == 1
    assert "attribution" in r.stderr


def test_commit_msg_accepts_the_words_inside_a_sentence(tmp_path):
    body = "The templates are generated with cdk synth and co-authored-by is not a trailer here."
    r = _commit_msg(tmp_path, f"docs: describe the templates\n\n{body}\n")
    assert r.returncode == 0, r.stderr


def _pre_push(stdin, **env):
    base = {k: v for k, v in os.environ.items() if k != "ALLOW_MAIN_PUSH"}
    return subprocess.run(
        [str(HOOKS / "pre-push"), "origin", "https://example.com/repo.git"],
        input=stdin,
        capture_output=True,
        text=True,
        check=False,
        cwd=ROOT,
        env={**base, **env},
    )


def test_pre_push_refuses_main():
    sha = "1" * 40
    r = _pre_push(f"refs/heads/mvp {sha} refs/heads/main {ZERO}\n")
    assert r.returncode == 1
    assert "open a pull request" in r.stderr
    assert "ALLOW_MAIN_PUSH=1" in r.stderr


def test_pre_push_refuses_deleting_main():
    r = _pre_push(f"(delete) {ZERO} refs/heads/main {'1' * 40}\n")
    assert r.returncode == 1


def test_pre_push_main_override_and_other_branches():
    # Deletions scan nothing, so these reach the end of the hook without gitleaks.
    main = f"(delete) {ZERO} refs/heads/main {'1' * 40}\n"
    assert _pre_push(main, ALLOW_MAIN_PUSH="1").returncode == 0
    assert _pre_push(f"(delete) {ZERO} refs/heads/feature {'1' * 40}\n").returncode == 0
